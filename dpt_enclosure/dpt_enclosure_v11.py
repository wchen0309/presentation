# DPT Premium Enclosure V11
# Detailed installation design source is generated in the current design session.
# Key mechanical design decisions:
# - removable upper shroud uses rear hooks, tapered locating pins, perimeter gasket,
#   and two front quarter-turn compression-latch envelopes;
# - lower inductor module uses guided male/female rails, four hard load pads,
#   and two captive front locking points;
# - service drawer reserves 76.2 mm slide height and 19.1 mm side-space envelope;
# - BUS+ / BUSN / BUS- are routed through a fixed rear three-pole backplane and
#   vertical feedthrough cassette so no loose high-power cable moves with drawer travel;
# - daily lid reserves a 6 mm smoked-PC panel, hidden touch-latch cavity,
#   pop-up plungers, torque-hinge envelope, and closed-lid interlock pocket;
# - external cosmetic fasteners are intentionally avoided; window and portal clamps
#   are internal-access service features.
